BEGIN;

CREATE TABLE IF NOT EXISTS livros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL UNIQUE,
    autor TEXT NOT NULL,
    edicao INTEGER NOT NULL CHECK (edicao > 0),
    genero TEXT NOT NULL,
    ano_publicacao INTEGER NOT NULL CHECK (ano_publicacao > 0),
    preco NUMERIC(10, 2) NOT NULL CHECK (preco >= 0),
    capacidade INTEGER NOT NULL CHECK (capacidade > 0),
    disponiveis INTEGER NOT NULL,
    ultimo_seq_pedido BIGINT NOT NULL DEFAULT 0 CHECK (ultimo_seq_pedido >= 0),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT livros_disponiveis_validos
        CHECK (disponiveis >= 0 AND disponiveis <= capacidade)
);

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS solicitacoes (
    request_id UUID PRIMARY KEY,
    tipo TEXT NOT NULL CHECK (tipo IN ('PEDIR', 'DEVOLVER')),
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    livro_id BIGINT NOT NULL REFERENCES livros(id) ON DELETE RESTRICT,
    emprestimo_id BIGINT,
    ordem_fila BIGINT,
    status TEXT NOT NULL CHECK (
        status IN ('RECEBIDO', 'AGUARDANDO', 'CONCLUIDO', 'REJEITADO')
    ),
    erro TEXT,
    payload_hash CHAR(64) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    concluido_em TIMESTAMPTZ,
    CONSTRAINT solicitacoes_formato_tipo CHECK (
        (tipo = 'PEDIR' AND ordem_fila IS NOT NULL)
        OR
        (tipo = 'DEVOLVER' AND ordem_fila IS NULL AND emprestimo_id IS NOT NULL)
    ),
    CONSTRAINT solicitacoes_erro_status CHECK (
        (status = 'REJEITADO' AND erro IS NOT NULL)
        OR
        (status <> 'REJEITADO')
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_solicitacoes_livro_ordem
    ON solicitacoes (livro_id, ordem_fila)
    WHERE ordem_fila IS NOT NULL;

CREATE INDEX IF NOT EXISTS ix_solicitacoes_fila
    ON solicitacoes (livro_id, tipo, status, ordem_fila);

CREATE TABLE IF NOT EXISTS emprestimos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    livro_id BIGINT NOT NULL REFERENCES livros(id) ON DELETE RESTRICT,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    borrow_request_id UUID NOT NULL UNIQUE
        REFERENCES solicitacoes(request_id) ON DELETE RESTRICT,
    emprestado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    devolvido_em TIMESTAMPTZ,
    CONSTRAINT emprestimos_datas_validas CHECK (
        devolvido_em IS NULL OR devolvido_em >= emprestado_em
    )
);

CREATE INDEX IF NOT EXISTS ix_emprestimos_ativos_livro
    ON emprestimos (livro_id)
    WHERE devolvido_em IS NULL;

CREATE INDEX IF NOT EXISTS ix_emprestimos_ativos_usuario
    ON emprestimos (usuario_id)
    WHERE devolvido_em IS NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'solicitacoes_emprestimo_fk'
    ) THEN
        ALTER TABLE solicitacoes
            ADD CONSTRAINT solicitacoes_emprestimo_fk
            FOREIGN KEY (emprestimo_id)
            REFERENCES emprestimos(id)
            ON DELETE RESTRICT;
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL REFERENCES solicitacoes(request_id) ON DELETE CASCADE,
    event_type TEXT NOT NULL,
    payload JSONB NOT NULL,
    publicado_em TIMESTAMPTZ,
    tentativas INTEGER NOT NULL DEFAULT 0 CHECK (tentativas >= 0),
    erro_publicacao TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_outbox_request_event UNIQUE (request_id, event_type)
);

CREATE INDEX IF NOT EXISTS ix_outbox_pendente
    ON outbox (criado_em, id)
    WHERE publicado_em IS NULL;

CREATE OR REPLACE FUNCTION definir_atualizado_em()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.atualizado_em = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_solicitacoes_atualizado_em ON solicitacoes;
CREATE TRIGGER trg_solicitacoes_atualizado_em
BEFORE UPDATE ON solicitacoes
FOR EACH ROW
EXECUTE FUNCTION definir_atualizado_em();

COMMIT;

